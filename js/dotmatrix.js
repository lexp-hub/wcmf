/**
 * Draws a dot-matrix text string onto a Canvas 2D context.
 */
export function drawDotMatrixText(ctx, text, x, y, options = {}) {
  const {
    dotSize = 3,
    dotGap = 2,
    charGap = 4,
    color = '#FFFFFF',
    dimColor = null, // for unlit background dots (classic VFD/LED style)
    align = 'left',
    shape = 'circle' // 'circle' or 'square'
  } = options;

  const chars = String(text).toUpperCase().split('');
  const charWidth = 5 * dotSize + 4 * dotGap;
  const charHeight = 7 * dotSize + 6 * dotGap;
  const totalWidth = chars.length * charWidth + Math.max(0, chars.length - 1) * charGap;

  let startX = x;
  if (align === 'center') {
    startX = x - totalWidth / 2;
  } else if (align === 'right') {
    startX = x - totalWidth;
  }

  const startY = y - charHeight / 2;

  chars.forEach((char, charIdx) => {
    const bitmap = DOT_MATRIX_5X7[char] || DOT_MATRIX_5X7[' '];
    const currCharX = startX + charIdx * (charWidth + charGap);

    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) {
        const isLit = bitmap[r] && bitmap[r][c] === 1;
        const dotX = currCharX + c * (dotSize + dotGap) + dotSize / 2;
        const dotY = startY + r * (dotSize + dotGap) + dotSize / 2;

        if (isLit) {
          ctx.fillStyle = color;
          ctx.beginPath();
          if (shape === 'circle') {
            ctx.arc(dotX, dotY, dotSize / 2, 0, Math.PI * 2);
          } else {
            ctx.rect(dotX - dotSize/2, dotY - dotSize/2, dotSize, dotSize);
          }
          ctx.fill();
        } else if (dimColor) {
          ctx.fillStyle = dimColor;
          ctx.beginPath();
          if (shape === 'circle') {
            ctx.arc(dotX, dotY, dotSize / 3, 0, Math.PI * 2);
          } else {
            ctx.rect(dotX - dotSize/3, dotY - dotSize/3, dotSize/1.5, dotSize/1.5);
          }
          ctx.fill();
        }
      }
    }
  });

  return { width: totalWidth, height: charHeight };
}

/**
 * Draws a dot-matrix icon onto a Canvas 2D context.
 */
export function drawDotMatrixIcon(ctx, iconName, x, y, options = {}) {
  const {
    dotSize = 3,
    dotGap = 2,
    color = '#FF4400',
    align = 'center'
  } = options;

  const bitmap = DOT_MATRIX_ICONS[iconName];
  if (!bitmap) return { width: 0, height: 0 };

  const iconWidth = 7 * dotSize + 6 * dotGap;
  const iconHeight = 7 * dotSize + 6 * dotGap;

  let startX = x;
  if (align === 'center') {
    startX = x - iconWidth / 2;
  } else if (align === 'right') {
    startX = x - iconWidth;
  }
  const startY = y - iconHeight / 2;

  ctx.fillStyle = color;
  for (let r = 0; r < 7; r++) {
    for (let c = 0; c < 7; c++) {
      if (bitmap[r] && bitmap[r][c] === 1) {
        const dotX = startX + c * (dotSize + dotGap) + dotSize / 2;
        const dotY = startY + r * (dotSize + dotGap) + dotSize / 2;
        ctx.beginPath();
        ctx.arc(dotX, dotY, dotSize / 2, 0, Math.PI * 2);
        ctx.fill();
      }
    }
  }

  return { width: iconWidth, height: iconHeight };
}

